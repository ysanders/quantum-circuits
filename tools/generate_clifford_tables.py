#!/usr/bin/env python3
"""Regenerate the tiny Clifford tables using exact Q(sqrt(2), i) arithmetic.

This is a development tool; importing quantum_circuits does not run it.
Run with --check to check the committed tables without changing them.
"""

from __future__ import annotations

import argparse
from collections import deque
from fractions import Fraction as F
from pathlib import Path

# A scalar is a + b*sqrt(2) + i*(c + d*sqrt(2)); a matrix is row-major.
Scalar = tuple[F, F, F, F]
Matrix = tuple[Scalar, Scalar, Scalar, Scalar]


def scalar(a=0, b=0, c=0, d=0) -> Scalar:
    return F(a), F(b), F(c), F(d)


def add(x: Scalar, y: Scalar) -> Scalar:
    return tuple(a + b for a, b in zip(x, y))


def neg(x: Scalar) -> Scalar:
    return tuple(-a for a in x)


def quadratic_product(x, y):
    return x[0] * y[0] + 2 * x[1] * y[1], x[0] * y[1] + x[1] * y[0]


def mul(x: Scalar, y: Scalar) -> Scalar:
    rr = quadratic_product(x[:2], y[:2])
    ii = quadratic_product(x[2:], y[2:])
    ri = quadratic_product(x[:2], y[2:])
    ir = quadratic_product(x[2:], y[:2])
    return rr[0] - ii[0], rr[1] - ii[1], ri[0] + ir[0], ri[1] + ir[1]


def conjugate(x: Scalar) -> Scalar:
    return x[0], x[1], -x[2], -x[3]


def product(a: Matrix, b: Matrix) -> Matrix:
    return tuple(
        add(mul(a[2 * row], b[col]), mul(a[2 * row + 1], b[2 + col]))
        for row in range(2)
        for col in range(2)
    )


def adjoint(a: Matrix) -> Matrix:
    return tuple(conjugate(a[j]) for j in (0, 2, 1, 3))


def scale(s: Scalar, a: Matrix) -> Matrix:
    return tuple(mul(s, x) for x in a)


def render() -> str:
    zero, one, i = scalar(), scalar(1), scalar(0, 0, 1)
    r = scalar(0, F(1, 2))
    omega = scalar(0, F(1, 2), 0, F(1, 2))
    identity = (one, zero, zero, one)
    x = (zero, one, one, zero)
    y = (zero, neg(i), i, zero)
    z = (one, zero, zero, neg(one))
    h = (r, r, r, neg(r))
    s = (one, zero, zero, i)
    paulis = (identity, x, y, z)
    bases = (identity, h, s, product(h, s), product(s, h), product(product(h, s), h))
    frames = tuple(product(p, base) for base in bases for p in paulis)
    labels = tuple(
        (p + base).replace("I", "") or "I"
        for base in ("I", "H", "S", "HS", "SH", "HSH")
        for p in ("I", "X", "Y", "Z")
    )
    actions = {
        (product(product(c, x), adjoint(c)), product(product(c, z), adjoint(c)))
        for c in frames
    }
    assert len(actions) == 24
    assert all(product(c, adjoint(c)) == identity for c in frames)

    phases = [one]
    for _ in range(7):
        phases.append(mul(phases[-1], omega))
    lookup = {
        scale(phase, c): (frame, k)
        for frame, c in enumerate(frames)
        for k, phase in enumerate(phases)
    }
    assert len(lookup) == 192
    table = tuple(tuple(lookup[product(a, b)] for b in frames) for a in frames)
    inverses = tuple(lookup[adjoint(c)] for c in frames)
    signed_paulis = {
        scale(scalar(sign), p): sign * axis
        for axis, p in enumerate((x, y, z), 1)
        for sign in (1, -1)
    }
    pauli_actions = tuple(
        tuple(signed_paulis[product(product(c, p), adjoint(c))] for p in (x, y, z))
        for c in frames
    )

    # Short exact H/S words in execution order, including global phase.
    words = {identity: ''}
    queue = deque((identity,))
    while queue:
        current = queue.popleft()
        for letter, gate in (('H', h), ('S', s)):
            successor = product(gate, current)
            if successor not in words:
                words[successor] = words[current] + letter
                queue.append(successor)
    assert words.keys() == lookup.keys()
    clifford_words = tuple(words[scale(phase, c)] for c in frames for phase in phases)
    lines = [
        '"""Generated by tools/generate_clifford_tables.py; do not edit by hand.',
        '',
        'C[4*b+p] = P[p] R[b], using matrix-product order.',
        'P = (I, X, Y, Z); R = (I, H, S, HS, SH, HSH).',
        'FRAME_PRODUCT[a][b] = (c, k) means C[a] C[b] = omega**k C[c].',
        'FRAME_INVERSE[a] = (c, k) means C[a]**-1 = omega**k C[c].',
        'PAULI_ACTION[a][j] encodes C[a] P[j] C[a]**-1 as +/-1,2,3 (X,Y,Z).',
        'CLIFFORD_WORDS[8*frame+phase] is an exact H/S word in execution order.',
        '"""',
        '',
        f'FRAME_LABELS = {labels!r}',
        '',
        'FRAME_PRODUCT = (',
    ]
    lines.extend(f'    {row!r},  # {label}' for label, row in zip(labels, table))
    lines += [')', '', f'FRAME_INVERSE = {inverses!r}', '', 'PAULI_ACTION = (']
    lines.extend(f'    {row!r},  # {label}' for label, row in zip(labels, pauli_actions))
    lines += [')', '', 'CLIFFORD_WORDS = (']
    lines.extend(f'    {word!r},' for word in clifford_words)
    lines += [')', '']
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'quantum_circuits' / '_clifford_tables.py'
    text = render()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Clifford tables are missing or out of date.')
        print('Clifford tables match exact regeneration.')
    else:
        path.write_text(text)
        print(f'Wrote {path}')


if __name__ == '__main__':
    main()
